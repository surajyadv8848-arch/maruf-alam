export interface GoogleDriveFile {
  id: string;
  name: string;
  mimeType: string;
  modifiedTime?: string;
  size?: string;
  webViewLink?: string;
}

/**
 * List files from Google Drive.
 * Can filter for files or search query.
 */
export async function listDriveFiles(
  token: string,
  searchQuery = ''
): Promise<GoogleDriveFile[]> {
  try {
    let q = "trashed = false";
    if (searchQuery.trim()) {
      const escaped = searchQuery.replace(/'/g, "\\'");
      q += ` and (name contains '${escaped}')`;
    }

    const url = new URL('https://www.googleapis.com/drive/v3/files');
    url.searchParams.set('q', q);
    url.searchParams.set('pageSize', '25');
    url.searchParams.set('orderBy', 'modifiedTime desc');
    url.searchParams.set('fields', 'files(id, name, mimeType, modifiedTime, size, webViewLink)');

    const res = await fetch(url.toString(), {
      headers: {
        Authorization: `Bearer ${token}`,
      },
    });

    if (!res.ok) {
      const errJson = await res.json().catch(() => ({}));
      throw new Error(errJson.error?.message || `Google Drive error: ${res.status}`);
    }

    const data = await res.json();
    return data.files || [];
  } catch (error) {
    console.error('Failed to list files from Google Drive:', error);
    throw error;
  }
}

/**
 * Upload a text or JSON report file to Google Drive using multipart upload
 */
export async function uploadReportToDrive(
  token: string,
  fileName: string,
  content: string,
  mimeType = 'text/plain'
): Promise<GoogleDriveFile> {
  const boundary = '-------HemoMatchBoundary' + Math.random().toString(36).substring(2);
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const metadata = {
    name: fileName,
    mimeType: mimeType,
    description: 'Generated by HemoMatch - Virtual Immunohematology Station (Made by Maruf)',
  };

  const multipartRequestBody =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    `Content-Type: ${mimeType}; charset=UTF-8\r\n\r\n` +
    content +
    closeDelimiter;

  const res = await fetch(
    'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,mimeType,modifiedTime,size,webViewLink',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': `multipart/related; boundary=${boundary}`,
      },
      body: multipartRequestBody,
    }
  );

  if (!res.ok) {
    const errJson = await res.json().catch(() => ({}));
    throw new Error(errJson.error?.message || `Failed to upload to Google Drive: ${res.status}`);
  }

  return await res.json();
}

/**
 * Download file content as text
 */
export async function getDriveFileContent(token: string, fileId: string): Promise<string> {
  const res = await fetch(`https://www.googleapis.com/drive/v3/files/${fileId}?alt=media`, {
    headers: {
      Authorization: `Bearer ${token}`,
    },
  });

  if (!res.ok) {
    throw new Error(`Failed to fetch file content: ${res.status}`);
  }

  return await res.text();
}

/**
 * Delete a file in Google Drive
 * CAUTION: Caller must confirm with user first!
 */
export async function deleteDriveFile(token: string, fileId: string): Promise<void> {
  const res = await fetch(`https://www.googleapis.com/drive/v3/files/${fileId}`, {
    method: 'DELETE',
    headers: {
      Authorization: `Bearer ${token}`,
    },
  });

  if (!res.ok && res.status !== 204) {
    const errJson = await res.json().catch(() => ({}));
    throw new Error(errJson.error?.message || `Failed to delete file from Google Drive: ${res.status}`);
  }
}
